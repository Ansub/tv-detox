#!/bin/sh
# Runs the checks in test/ on your laptop: no TV, no emulator. Needs Java 17 and the Android SDK,
# like build.sh (the SDK only for android.jar, to compile against).
set -e
cd "$(dirname "$0")"

[ -n "$JAVA_HOME" ] || for j in /opt/homebrew/opt/openjdk@17 /usr/local/opt/openjdk@17 /usr/lib/jvm/java-17-openjdk-amd64; do [ -d "$j" ] && JAVA_HOME=$j && break; done
[ -n "$JAVA_HOME" ] && export PATH="$JAVA_HOME/bin:$PATH"
SDK=${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}
[ -n "$SDK" ] || for d in /opt/homebrew/share/android-commandlinetools "$HOME/Library/Android/sdk" "$HOME/Android/Sdk"; do [ -d "$d" ] && SDK=$d && break; done
# Any platform will do to compile against: the tests only run code that doesn't touch Android.
JAR=$SDK/platforms/android-34/android.jar
[ -f "$JAR" ] || JAR=$(ls "$SDK"/platforms/android-*/android.jar 2>/dev/null | sort -V | tail -1)
[ -f "$JAR" ] || { echo "Android SDK not found. Set ANDROID_HOME and install a platform (platforms;android-34)." >&2; exit 1; }

rm -rf out/test; mkdir -p out/test
# The app list is generated by build.sh; the tests don't read it, so a stand-in will do.
mkdir -p out/test/gen/com/ansub/tvhome
echo 'package com.ansub.tvhome; final class Apps { static final String[] LIST = {}; }' > out/test/gen/com/ansub/tvhome/Apps.java
# shellcheck disable=SC2046 # javac wants one argument per file
javac -nowarn -Xlint:-options -encoding UTF-8 -source 1.8 -target 1.8 -cp "$JAR" \
  -d out/test/classes $(find src test out/test/gen -name "*.java")
java -cp "out/test/classes:$JAR" com.ansub.tvhome.Tests
